#!/usr/bin/env python3
"""
Compile locales/zh_CN.tsv, locales/zh_CN_aliases.tsv, locales/zh_CN_manuals.tsv,
and tools/STCharacters.txt into compact C++ embedded data header:
    sys/praat_i18n_data.h

Design:
  - Raw UTF-8 TSV payloads embedded as static const unsigned char[] arrays
    (compiles in < 0.2s, zero static constructors, zero heap fragmentation).
  - Compact sorted Simplified -> Traditional codepoint table (uint32_t pairs)
    for O(log N) binary search during one-time startup table generation.
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCALES_DIR = ROOT / "locales"
ST_PATH = ROOT / "tools" / "STCharacters.txt"
OUT_PATH = ROOT / "sys" / "praat_i18n_data.h"


def parse_st_pairs(path: Path) -> list[tuple[int, int]]:
    pairs: dict[int, int] = {}
    if not path.exists():
        return []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        src = parts[0]
        dst = parts[1].split()[0]
        if len(src) == 1 and len(dst) == 1 and src != dst:
            pairs[ord(src)] = ord(dst)
    return sorted(pairs.items())


def strip_comments_tsv(path: Path) -> bytes:
    lines = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        if not raw or raw.startswith("#"):
            continue
        lines.append(raw)
    return ("\n".join(lines) + "\n").encode("utf-8")


def emit_byte_array(name: str, data: bytes) -> list[str]:
    out = [
        f"static const unsigned char {name} [{len(data) + 1}] = {{",
    ]
    row_size = 24
    for i in range(0, len(data), row_size):
        chunk = data[i : i + row_size]
        out.append("\t" + ",".join(str(b) for b in chunk) + ",")
    out.append("\t0")
    out.append("};")
    out.append(f"static constexpr size_t {name}_size = {len(data)};")
    return out


def main() -> None:
    ui_bytes = strip_comments_tsv(LOCALES_DIR / "zh_CN.tsv")
    alias_bytes = strip_comments_tsv(LOCALES_DIR / "zh_CN_aliases.tsv")
    manual_bytes = strip_comments_tsv(LOCALES_DIR / "zh_CN_manuals.tsv")
    st_pairs = parse_st_pairs(ST_PATH)

    lines: list[str] = [
        "#ifndef _praat_i18n_data_h_",
        "#define _praat_i18n_data_h_",
        "/* Auto-generated by tools/build_i18n_data.py from locales/*.tsv and tools/STCharacters.txt.",
        " * Do not edit manually; edit locales/zh_CN.tsv or locales/zh_CN_manuals.tsv and re-run.",
        " */",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
    ]

    lines.extend(emit_byte_array("kPraatI18nUiTsv", ui_bytes))
    lines.append("")
    lines.extend(emit_byte_array("kPraatI18nAliasesTsv", alias_bytes))
    lines.append("")
    lines.extend(emit_byte_array("kPraatI18nManualsTsv", manual_bytes))
    lines.append("")

    lines.append("struct PraatS2TPair { uint32_t simp; uint32_t trad; };")
    lines.append(f"static constexpr PraatS2TPair kPraatS2TTable [{len(st_pairs)}] = {{")
    for i in range(0, len(st_pairs), 6):
        chunk = st_pairs[i : i + 6]
        lines.append("\t" + ", ".join(f"{{0x{s:04X}u,0x{t:04X}u}}" for s, t in chunk) + ",")
    lines.append("};")
    lines.append(f"static constexpr size_t kPraatS2TTable_size = {len(st_pairs)};")
    lines.append("")
    lines.append("#endif")

    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(
        f"Generated {OUT_PATH} | UI={len(ui_bytes):,}B | Aliases={len(alias_bytes):,}B "
        f"| Manuals={len(manual_bytes):,}B | S2T={len(st_pairs)} pairs"
    )


if __name__ == "__main__":
    main()
